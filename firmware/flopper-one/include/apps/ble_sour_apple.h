        void on_enter() override
        {

            if (!started_)
                start_();
            log::line("BLE", "sour enter");

            randomSeed(analogRead(0));
            esp_ble_tx_power_set(ESP_BLE_PWR_TYPE_ADV, MAX_TX_POWER);
            flopper::ble::set_static_random_addr("D3:16:12:34:56:72");

            NimBLEServer *pServer = NimBLEDevice::createServer();
            pAdvertising = pServer->getAdvertising();
        }

        void on_exit() override
        {
            if (pAdvertising)
                pAdvertising->stop();
            if (NimBLEDevice::isInitialized())
                NimBLEDevice::deinit(true);
            started_ = false;
            pAdvertising = nullptr;
            server_ = nullptr;
            log::line("BLE", "sour exit");
        }

        void draw() override {}

        void tick() override
        {
            NimBLEAdvertisementData oAdvertisementData;

            int device_choice = random(2);
            if (device_choice == 0)
            {
                int index = random(13);
                oAdvertisementData.addData(std::vector<uint8_t>(
                    SHORT_DEVICES[index],
                    SHORT_DEVICES[index] + sizeof(SHORT_DEVICES[index])));
            }
            else
            {
                int index = random(17);
                oAdvertisementData.addData(std::vector<uint8_t>(
                    DEVICES[index],
                    DEVICES[index] + sizeof(DEVICES[index])));
            }

            pAdvertising->setConnectableMode(BLE_GAP_CONN_MODE_NON);
            pAdvertising->enableScanResponse(false);
            pAdvertising->setAdvertisementData(oAdvertisementData);

            pAdvertising->setMinInterval(0x20);
            pAdvertising->setMaxInterval(0x20);

            Serial.println("Sending Advertisement...");
            pAdvertising->start();
            delay(delayMilliseconds);
            pAdvertising->stop();
        }

        void on_input(InputEvent e) override
        {
            if (e == InputEvent::LEFT)
            {
                exit();
                return;
            }
        }

